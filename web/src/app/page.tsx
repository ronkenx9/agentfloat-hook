import { fetchState } from "@/lib/api";
import { loadRealState } from "@/lib/brain";
import { getDemoState } from "@/lib/demo";
import { Masthead } from "@/components/Masthead";
import { StudioRunway } from "@/components/StudioRunway";
import { ModeDial } from "@/components/ModeDial";
import { ProposalCard } from "@/components/ProposalCard";
import { ProofTier } from "@/components/ProofTier";
import { EditorialImage } from "@/components/EditorialImage";
import { LiveTicker } from "@/components/LiveTicker";
import { JournalFeed } from "@/components/JournalFeed";
import { HeroMetrics } from "@/components/HeroMetrics";
import { SandboxView } from "@/components/SandboxView";

// Re-render every 30 seconds so live proposals/scores show up without manual refresh.
export const revalidate = 30;

interface SearchParams {
  demo?: string;
  tab?: string;
}

export default async function Home({
  searchParams,
}: {
  searchParams: Promise<SearchParams>;
}) {
  const params = await searchParams;
  const useDemo = params.demo === "1";
  const tab = params.tab === "sandbox" ? "sandbox" : "dashboard";

  let state;
  if (useDemo) {
    state = getDemoState();
  } else {
    const live = await fetchState();
    if (live) {
      state = live;
    } else {
      // No live agent API reachable (e.g. a bare Vercel deploy before the API
      // is hosted). Try the brain filesystem; if that's empty too, fall back to
      // the demo dataset so the public page renders something coherent. The
      // `isDemo` badge in the Masthead keeps that honest.
      const local = loadRealState();
      state = local.strategies.length > 0 ? local : getDemoState();
    }
  }
  const hasProposals = state.proposals.length > 0;

  if (tab === "sandbox") {
    return (
      <main className="min-h-screen flex flex-col bg-paper text-ink">
        <Masthead isDemo={state.isDemo} agentAlive={state.health.agentAlive} activeTab={tab} />
        
        {/* Live data band */}
        <LiveTicker initialState={state} />

        {/* Sandbox view */}
        <SandboxView />

        {/* Colophon */}
        <footer className="bg-ink text-paper py-10 mt-auto">
          <div
            className="max-w-[1180px] mx-auto px-6 flex flex-col md:flex-row items-baseline justify-between gap-4 text-[10px] mono uppercase tracking-[0.12em]"
            style={{ color: "var(--rule)" }}
          >
            <span>AgentFloat · Yield routing that learns</span>
            <span style={{ color: "var(--ink-faint)" }}>
              Set in Source Serif 4 + JetBrains Mono · Vol. I MMXXVI
            </span>
          </div>
        </footer>
      </main>
    );
  }

  return (
    <main className="min-h-screen flex flex-col">
      <Masthead isDemo={state.isDemo} agentAlive={state.health.agentAlive} activeTab={tab} />

      {/* Live data band — sits right under masthead */}
      <LiveTicker initialState={state} />

      {/* ─────────── PLATE 01 — Hero ─────────── */}
      <EditorialImage
        src="/hero.png"
        alt="A figure reading a folder — the system at work"
        heightRatio={0.85}
        position="right"
        overlayPosition="left"
        overlayTone="ink"
        overlay={
          <div>
            <span className="mono text-[10px] uppercase tracking-[0.12em] text-ink-soft">
              № 01 · The studio
            </span>
            <h1 className="serif text-[48px] md:text-[72px] leading-[1.03] tracking-tight mt-4 max-w-[18ch]">
              An autonomous AI developer studio building <em className="italic">web3 infrastructure</em>.
            </h1>
            <p className="text-lg text-ink-soft mt-5 max-w-[42ch] leading-relaxed">
              AgentFloat Studio builds and runs a portfolio of protocols, using self-generated yield to power its own LLM runtimes, security auditing, and on-chain upgrades.
            </p>
          </div>
        }
      />

      {/* ─────────── Hero metrics row ─────────── */}
      <HeroMetrics />

      {/* ─────────── Journal shipping log ─────────── */}
      <JournalFeed />

      {/* ─────────── Compute Runway + Mode dial ─────────── */}
      <section className="max-w-[1180px] mx-auto px-6 pt-2 pb-14 w-full">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-px bg-rule border border-rule">
          <div className="bg-paper">
            <StudioRunway />
          </div>
          <div className="bg-paper">
            <ModeDial mode={state.mode} isDemo={state.isDemo} />
          </div>
        </div>
      </section>
      {/* ─────────── AI Code Proposals ─────────── */}
      <section className="max-w-[1180px] mx-auto px-6 pt-10 pb-4 w-full">
        <div className="pb-3 border-b border-rule">
          <span className="mono text-[10px] uppercase text-ink-soft tracking-[0.12em]">
            № 02 · AI Code Proposals
          </span>
          <h2 className="serif text-2xl mt-2 tracking-tight">
            Autonomous upgrades generated by the orchestrator.
          </h2>
        </div>
      </section>

      {/* ─────────── Proposals feed ─────────── */}
      <section className="bg-paper-2/30">
        <div className="max-w-[1180px] mx-auto px-6 py-8 w-full">
          {!hasProposals ? (
            <div className="text-center py-16 text-ink-soft">
              <p className="serif text-2xl mb-3">No proposals yet.</p>
              <p className="text-sm max-w-[40ch] mx-auto">
                The orchestrator runs every ~hour. Once it generates its first proposal, it will
                appear here with the AI's reasoning and any deploy outcomes.
              </p>
              <p className="text-xs mt-4">
                <a href="/?demo=1" className="mono uppercase underline decoration-rule hover:text-accent">
                  View demo →
                </a>
              </p>
            </div>
          ) : (
            <div className="flex flex-col gap-5">
              {state.proposals.map((p) => (
                <ProposalCard key={p.id} proposal={p} explorerBase={state.contracts.explorerBase} />
              ))}
            </div>
          )}
        </div>
      </section>

      {/* ─────────── Proof Tier ─────────── */}
      <ProofTier state={state} />

      {/* ─────────── Final colophon ─────────── */}
      <footer className="bg-ink text-paper py-10">
        <div
          className="max-w-[1180px] mx-auto px-6 flex flex-col md:flex-row items-baseline justify-between gap-4 text-[10px] mono uppercase tracking-[0.12em]"
          style={{ color: "var(--rule)" }}
        >
          <span>AgentFloat Studio</span>
          <span style={{ color: "var(--ink-faint)" }}>
            Set in Source Serif 4 + JetBrains Mono · Vol. I MMXXVI
          </span>
        </div>
      </footer>
    </main>
  );
}
